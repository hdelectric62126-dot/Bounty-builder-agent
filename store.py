class PostgresConnection:
    def __init__(self, url):
        self.raw = psycopg.connect(url, row_factory=dict_row,
                                   options="-c search_path=bounty_builder,public")

    def __enter__(self): return self
    def __exit__(self, kind, value, traceback):
        self.raw.rollback() if kind else self.raw.commit()
        self.raw.close()

    def executescript(self, script):
        self.raw.execute(script)

    def execute(self, query, params=()):
        if query.strip().upper().startswith("PRAGMA"):
            return EmptyCursor()
        sql = query.replace("BEGIN IMMEDIATE", "BEGIN")
        sql = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, flags=re.I)
        sql = re.sub(r"VALUES\s*\(NULL,", "VALUES(DEFAULT,", sql, flags=re.I)
        sql = sql.replace("SUM(status='ACCREDITED')", "COUNT(*) FILTER (WHERE status='ACCREDITED')")
        sql = sql.replace("SUM(status='APPROVED')", "COUNT(*) FILTER (WHERE status='APPROVED')")
        sql = sql.replace("SUM(status='REJECTED')", "COUNT(*) FILTER (WHERE status='REJECTED')")
        replace_review = bool(re.search(r"INSERT\s+OR\s+REPLACE\s+INTO\s+work_reviews", query, re.I))
        if replace_review:
            sql = re.sub(r"INSERT\s+OR\s+REPLACE\s+INTO", "INSERT INTO", sql, flags=re.I)
            sql += " ON CONFLICT(evidence_id) DO UPDATE SET decision=excluded.decision, payload=excluded.payload, created_at=excluded.created_at"
        elif re.search(r"INSERT\s+OR\s+IGNORE", query, re.I) and "ON CONFLICT" not in sql.upper():
            sql += " ON CONFLICT DO NOTHING"
        sql = sql.replace("?", "%s")
        wants_id = bool(re.match(r"\s*INSERT INTO (outcomes|client_requests|client_jobs)\b", sql, re.I))
        if wants_id and "RETURNING" not in sql.upper():
            sql += " RETURNING id"
        cursor = self.raw.execute(sql, params) if params else self.raw.execute(sql)
        return PgCursor(cursor, wants_id)


class PgCursor:
    def __init__(self, cursor, capture_id=False):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.lastrowid = None
        if capture_id:
            row = cursor.fetchone()
            self.lastrowid = row["id"] if row else None
    def fetchone(self): return self.cursor.fetchone()
    def fetchall(self): return self.cursor.fetchall()
    def __iter__(self): return iter(self.cursor)


class EmptyCursor:
    rowcount = 0
    lastrowid = None
    def fetchone(self): return None
    def fetchall(self): return []
    def __iter__(self): return iter(())


class Store:
    def __init__(self, path: str):
        self.path = path
        self.postgres = path.startswith(("postgres://", "postgresql://"))
        if self.postgres and psycopg is None:
            raise RuntimeError("psycopg is required when DATABASE_URL is configured")
        with self.connect() as db:
            if self.postgres:
                ready = db.execute("SELECT COUNT(*) ready FROM migration_state").fetchone()
                if ready is None:
                    raise RuntimeError("PostgreSQL schema is not initialized")
            else:
                db.execute("PRAGMA journal_mode=WAL")
                db.executescript(SCHEMA)

    def connect(self):
        if self.postgres:
            return PostgresConnection(self.path)
        db = sqlite3.connect(self.path)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA busy_timeout=5000")
        return db

    def audit(self, event, details):
        with self.connect() as db:
            db.execute("INSERT INTO audit_log VALUES(NULL,?,?,?)",
                       (event, json.dumps(details), now()))

    def save_opportunity(self, item):
        with self.connect() as db:
            db.execute("""INSERT INTO opportunities VALUES(NULL,?,?,?,?,?,?,?,?,?,?,?)
              ON CONFLICT(external_id) DO UPDATE SET title=excluded.title,
              url=excluded.url, repository=excluded.repository, reward=excluded.reward,
              license=excluded.license, status=excluded.status,
              risk_score=excluded.risk_score, expected_value=excluded.expected_value,
              reason=excluded.reason""", (
                item["external_id"], item["title"], item["url"], item["repository"],
                item["reward"], item["license"], item["status"], item["risk_score"],
                item["expected_value"], item["reason"], now()))
            for key, agent in (("repository_analysis", "repository_analyst"),
                               ("risk_compliance", "risk_compliance_agent"),
                               ("solution_plan", "solution_planner")):
                if item.get(key) is not None:
                    db.execute("""INSERT INTO agent_records VALUES(NULL,?,?,?,?)
                      ON CONFLICT(external_id,agent) DO UPDATE SET
                      payload=excluded.payload, created_at=excluded.created_at""",
                      (item["external_id"], agent, json.dumps(item[key]), now()))

