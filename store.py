    def enqueue_work(self, opportunity_id, deliberation):
        stage = ({"AUTO_APPROVE_ISOLATED_BUILD": "READY_FOR_ISOLATED_BUILD",
                  "QUEUE_FOR_DANIEL_APPROVAL": "AWAITING_DANIEL_APPROVAL"}
                 .get(deliberation["recommendation"], "TRAINING_REQUIRED"))
        with self.connect() as db:
            db.execute("""INSERT INTO work_queue VALUES(NULL,?,?,?,?,?)
              ON CONFLICT(opportunity_id) DO UPDATE SET stage=excluded.stage,
              deliberation=excluded.deliberation, updated_at=excluded.updated_at""",
              (opportunity_id, stage, json.dumps(deliberation), now(), now()))
        return stage

    def work_queue(self, limit=100):
        with self.connect() as db:
            rows = db.execute("""SELECT q.*, p.title, p.repository, p.reward,
              p.expected_value, p.url FROM work_queue q JOIN opportunities p
              ON p.id=q.opportunity_id ORDER BY p.expected_value DESC LIMIT ?""", (limit,))
            return [{**dict(row), "deliberation": json.loads(row["deliberation"])} for row in rows]

    def expire_stale_work(self):
        """Mark non-current queued bounty work stale without deleting history."""
        with self.connect() as db:
            cursor = db.execute("""UPDATE work_queue SET stage='STALE_NOT_CURRENT', updated_at=?
              WHERE opportunity_id IN (SELECT id FROM opportunities WHERE status!='APPROVED')
              AND stage IN ('AWAITING_DANIEL_APPROVAL','READY_FOR_ISOLATED_BUILD',
                            'TRAINING_REQUIRED','BLOCKED_MODEL_NOT_CONFIGURED')""", (now(),))
            return cursor.rowcount

    def claim_ready_bounty(self):
        """Claim one fresh internally authorized bounty for isolated building."""
        with self.connect() as db:
            row = db.execute("""SELECT q.*, p.external_id, p.title, p.repository,
              p.reward, p.expected_value, p.url FROM work_queue q
              JOIN opportunities p ON p.id=q.opportunity_id
              WHERE q.stage='READY_FOR_ISOLATED_BUILD' AND p.status='APPROVED'
              ORDER BY p.expected_value DESC, q.id ASC LIMIT 1""").fetchone()
            if not row:
                return None
            cursor = db.execute("""UPDATE work_queue SET stage='BUILDING', updated_at=?
              WHERE id=? AND stage='READY_FOR_ISOLATED_BUILD'""", (now(), row["id"]))
            if cursor.rowcount != 1:
                return None
            result = dict(row)
            result["stage"] = "BUILDING"
            result["deliberation"] = json.loads(result["deliberation"])
            return result

    def set_bounty_stage(self, queue_id, stage):
        allowed = {
            'READY_FOR_ISOLATED_BUILD', 'BUILDING', 'AWAITING_DANIEL_DELIVERY_REVIEW',
            'TESTS_FAILED', 'BUILD_FAILED', 'BLOCKED_MODEL_NOT_CONFIGURED',
            'STALE_NOT_CURRENT',
        }
        if stage not in allowed:
            raise ValueError("invalid bounty stage")
        with self.connect() as db:
            cursor = db.execute("UPDATE work_queue SET stage=?, updated_at=? WHERE id=?",
                                (stage, now(), queue_id))
            if cursor.rowcount != 1:
                raise KeyError("work queue item not found")
        return stage

    def agent_activity(self):
        with self.connect() as db:
            records = {row["agent"]: row["count"] for row in db.execute(
                "SELECT agent, COUNT(*) count FROM agent_records GROUP BY agent")}
            scans = db.execute("SELECT COUNT(*) count FROM audit_log WHERE event LIKE 'scout_%'").fetchone()["count"]
            proposals = db.execute("SELECT COUNT(*) count FROM learning_proposals").fetchone()["count"]
            return {
                "opportunity_scout": scans,
                "repository_analyst": records.get("repository_analyst", 0),
                "risk_compliance_agent": records.get("risk_compliance_agent", 0),
                "solution_planner": records.get("solution_planner", 0),
                "performance_learner": proposals,
                "historical_experience": self.experience_stats()["cases"],
                "delivery_reviews": db.execute("SELECT COUNT(*) count FROM work_reviews").fetchone()["count"],
                "deep_deliberations": db.execute("SELECT COUNT(*) count FROM work_queue").fetchone()["count"],
                "practice": self.practice_stats(),
                "teacher": self.teacher_stats(),
            }

    def stats(self):
        with self.connect() as db:
            row = db.execute("""SELECT COUNT(*) found,
              SUM(status='APPROVED') approved,
              SUM(status='REJECTED') rejected,
              COALESCE(SUM(CASE WHEN status='APPROVED' THEN expected_value ELSE 0 END),0)
              expected_value FROM opportunities""").fetchone()
            money = db.execute("SELECT COALESCE(SUM(income-cost),0) amount FROM outcomes").fetchone()["amount"]
            return {**dict(row), "realized_income": round(money, 2),
                    "agent_activity": self.agent_activity()}

